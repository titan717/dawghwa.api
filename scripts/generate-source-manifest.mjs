#!/usr/bin/env node
/**
 * Generates src/lib/providers/manifest.generated.ts from the adapter sources.
 *
 * For every adapter it records the display name, the base URL and the exact
 * set of domains named in canHandle(). Those domains are the *only* hosts the
 * API will fetch user-supplied URLs from for that source (SSRF protection), and
 * they replace upstream's substring matching (`url.includes(...)`).
 *
 * Usage: node scripts/generate-source-manifest.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src/lib/scrapers");
const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && !["base.ts", "index.ts"].includes(f)).sort();
const entries = [];
for (const file of files) {
  const src = readFileSync(join(dir, file), "utf8");
  const name = src.match(/getName\(\)\s*:\s*string\s*\{\s*return\s*(["'`])(.+?)\1\s*;/)?.[2];
  const base =
    src.match(/BASE_URL\s*=\s*["'`](https?:\/\/[^"'`]+)["'`]/)?.[1] ??
    src.match(/getBaseUrl\(\)\s*:\s*string\s*\{\s*return\s*["'`](https?:\/\/[^"'`]+)["'`]/)?.[1];
  const canHandle = src.match(/canHandle\([^)]*\)\s*:\s*boolean\s*\{([\s\S]*?)\n  \}/)?.[1] ?? "";
  const domains = new Set(
    [...canHandle.matchAll(/includes\(\s*["'`]([^"'`]+)["'`]\s*\)/g)].map((m) => m[1].toLowerCase()).filter((d) => d.includes(".")),
  );
  if (base) domains.add(new URL(base).hostname.replace(/^www\./, ""));
  if (!name) throw new Error(`Could not find getName() in ${file}`);
  entries.push({ file, name, domains: [...domains].sort() });
}
const out = `// AUTO-GENERATED by scripts/generate-source-manifest.mjs. Do not edit by hand.
// Domains each adapter is allowed to fetch user-supplied URLs from.
export const ADAPTER_DOMAINS: Record<string, readonly string[]> = {
${entries.map((e) => `  ${JSON.stringify(e.name)}: ${JSON.stringify(e.domains)}, // ${e.file}`).join("\n")}
};
`;
writeFileSync(join(process.cwd(), "src/lib/providers/manifest.generated.ts"), out);
console.log(`Wrote ${entries.length} adapters`);
